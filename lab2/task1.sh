<<'Разработать сценарий, который ведёт в файле /tmp/run.log последовательный
журнал запусков:
-в конец журнала добавляет строку с датой и временем запуска сценария
(используйте команду date для фиксации даты и времени запуска
сценария);
-в стандартный вывод (stdout) - выводит фразу "Hello, World!";
-в стандартный вывод ошибок (stderr) - выводит количество предыдущих
запусков программы'

#!/bin/bash

LOG=/tmp/run.log
touch "$LOG"

prev_count=$(wc -l < "$LOG")  

date +"%Y-%m-%d %H:%M:%S" >> "$LOG" <<'+"..." строка формата'

echo "Hello, World!"
echo "Количество предыдущих запусков: $prev_count" >&2

exit 0