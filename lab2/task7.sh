<<'Написать скрипт filter_numbers.sh, который:
-принимает список чисел как аргументы ($@);
-перебирает числа;
-если число делится на 3 — пропускает его;
-если число чётное — выводит его в файл even.txt;
-если число нечётное — выводит его в файл odd.txt;
-в конце выводит сообщение о количестве обработанных чисел'

#!/bin/bash

> even.txt
> odd.txt

count=0

for num in "$@"; do
    if ! [[ "$num" =~ ^-?[0-9]+$ ]]; then
        echo "Пропуск (не число): $num" >&2
        continue
    fi

    count=$((count + 1))

    if (( num % 3 == 0 )); then
        continue
    fi

    if (( num % 2 == 0 )); then
        echo "$num" >> even.txt
    else
        echo "$num" >> odd.txt
    fi
done

echo "Обработано чисел: $count"

