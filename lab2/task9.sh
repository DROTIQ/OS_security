<<'Подготовьте данные для тестирования и напишите скрипт analyze_sales.sh,
который:
-принимает имя CSV-файла с данными о продажах как аргумент;
-читает файл и выводит:
1) общую сумму продаж;
2) среднюю стоимость продажи;
3) самую дорогую продажу;
-охраняет результаты в файл sales_report.txt с помощью tee'

#!/bin/bash

if [ $# -ne 1 ]; then
    echo "Использование: $0 <file.csv>" >&2
    exit 1
fi

CSV="$1"

if [ ! -f "$CSV" ]; then
    echo "Файл не найден: $CSV" >&2
    exit 1
fi

awk -F, '
    NR > 1 && $3 != "" {
        sum += $3
        n++
        if ($3 > max) max = $3
    }
    END {
        if (n > 0)
            printf "Общая сумма продаж: %.2f\nСредняя стоимость продажи: %.2f\nСамая дорогая продажа: %.2f\n", sum, sum/n, max
        else
            printf "Общая сумма продаж: 0\nСредняя стоимость продажи: 0\nСамая дорогая продажа: 0\n"
    }
' "$CSV" | tee sales_report.txt