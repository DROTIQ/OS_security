<<'Разработать сценарий поиска дубликатов файлов (файлы, с одинаковым
содержимым), который выводит сначала количество дубликатов, затем имя
файла. Файлы без дубликатов выводиться не должны'

#!/bin/bash

DIR="${1:-.}"

find "$DIR" -type f -exec md5sum {} + \
  | sort \
  | awk '
    {
        hash = $1  - первое поле текущей строки (у нас строка: хэш + путь к файлу)
        $1 = ""
        sub(/^ +/, "")
        count[hash]++
        files[hash] = files[hash] "\n  " $0
    }
    END {
        for (h in count)
            if (count[h] > 1)
                print count[h] " дубликатов:" files[h]
    }'



